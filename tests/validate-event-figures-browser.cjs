'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs/promises'),path=require('node:path');
const {pathToFileURL}=require('node:url'),{chromium}=require('playwright');
const workspaceProject=require('./fixtures/workspace-project.cjs');
const {pack,unpack}=require('../scripts/browser-storage');

(async()=>{
  const browser=await chromium.launch({channel:'chrome',headless:true});
  try{
    const page=await browser.newPage({viewport:{width:1580,height:980}}),errors=[];
    page.on('pageerror',e=>errors.push(e.message));page.setDefaultTimeout(12000);
    await page.goto(pathToFileURL(path.resolve(process.argv[2]||path.join(__dirname,'../dist/Neuropixels-Explorer.html'))).href);
    const picker=page.waitForEvent('filechooser');await page.locator('[data-project-action=open-project]:visible').first().click();
    const file=await workspaceProject(),source=await unpack(new Blob([file.buffer]));
    const metadata=source.assets.find(a=>a.name==='explorer-events.json'),events=JSON.parse(await metadata.blob.text());
    const replies=events.events.filter((e,i)=>i%2).map(e=>({...e,id:'lick'+e.id,type:'lick',start:e.start+.3,conditions:{}}));
    events.events.push(...events.events.map((e,i)=>({...e,id:'cue'+i,type:'cue',conditions:{direction:i%2?'left':'right'}})));
    events.events.push(...replies);
    metadata.blob=new Blob([JSON.stringify(events)]);
    file.buffer=Buffer.from(await pack(source.project,source.assets,source.annotations).arrayBuffer());
    await (await picker).setFiles(file);
    await page.locator('.sw-space [data-unit]').first().waitFor();
    await page.locator('#event-analysis-button').click();
    const set=name=>page.locator('[name='+name+']:visible');
    await set('eventType').selectOption('image_change');
    assert.equal(await set('conditionField').inputValue(),'');
    assert.equal(await set('conditionField').locator('option[value=trial_outcome]').count(),0);
    await set('conditionField').selectOption('@response-label');
    assert(await page.locator('[data-ea-run]').isDisabled());
    await set('responseLabel').selectOption(JSON.stringify(['experiment','lick']));
    await page.locator('[data-ea-run]').click();await page.locator('[data-ea-unit]').first().waitFor();
    const panel=id=>page.locator('[data-ef-panel='+id+']:visible');
    const canvas=page.locator('[data-ef-canvas]:visible'), save=page.locator('[data-ef-export]:visible');
    assert.equal(await panel('review').getAttribute('aria-pressed'),'true');
    assert.equal(await canvas.count(),0);
    const images=new Set();
    const exportPanel=async (id,fromCanvas=false)=>{
      const pending=page.waitForEvent('download');
      if(fromCanvas){
        await canvas.click({button:'right'});
        await page.locator('.event-figures .ea-image-menu button').click();
      }else await save.click();
      const file=await pending;const bytes=await fs.readFile(await file.path());
      assert.match(file.suggestedFilename(),/\.png$/i);
      assert.equal(bytes.subarray(1,4).toString(),'PNG');assert(bytes.readUInt32BE(16)>=1000);
      const corner=await page.evaluate(async bytes=>{
        const bitmap=await createImageBitmap(new Blob([Uint8Array.from(bytes)],{type:'image/png'}));
        const c=document.createElement('canvas'),ctx=c.getContext('2d');ctx.drawImage(bitmap,0,0,1,1,0,0,1,1);
        return [...ctx.getImageData(0,0,1,1).data];
      },Array.from(bytes));
      assert.deepEqual(corner,[255,255,255,255],'opaque white '+id+' export');
      images.add(require('node:crypto').createHash('sha256').update(bytes).digest('hex'));
    };
    await panel('J').click();await canvas.waitFor();
    assert(await canvas.evaluate(c=>!!c.closest('#analysis-pages > [role="tabpanel"]:not([hidden]) [data-ea-results]')));
    assert.equal(await page.locator(':modal').count(),0);
    assert.equal(await page.locator('[data-ea-unit]:visible').count(),0);
    assert.match(await canvas.getAttribute('aria-label'),/image_change → lick \[0\.15, 0\.75\) s/);await exportPanel('J');
    await exportPanel('J',true);assert.equal(images.size,1,'both export actions save the same white figure');
    await page.setViewportSize({width:390,height:844});
    await page.waitForFunction(()=>{const s=document.querySelector('.event-figures:not([hidden]) .ef-scroll');return s.clientWidth>0 && s.clientWidth<390 && s.scrollWidth>=560 && document.documentElement.scrollWidth<=390;});
    await page.setViewportSize({width:1580,height:980});
    const group=page.locator('[data-ef-group]:visible');
    await group.click();await page.locator('[data-ef-group][aria-pressed=true]').waitFor();
    await panel('K').click();await exportPanel('K');
    await panel('L').click();
    const units=page.locator('[data-ef-units]'),unitToggle=page.locator('.ef-picker>summary');
    await unitToggle.click();await units.selectOption(['11','33']);await unitToggle.click();
    const trial=i=>page.locator('[data-ef-trial="'+i+'"]:visible');
    await trial(0).selectOption({index:1});await trial(1).selectOption({index:2});
    const choices=await Promise.all([trial(0).inputValue(),trial(1).inputValue()]);
    await exportPanel('L');
    await panel('M').click();
    const end=set('efEndMs');await end.fill('190');await end.press('Tab');
    await set('efBaseline').check();await exportPanel('M');
    assert.equal(images.size,4);
    await panel('L').click();
    assert.deepEqual(await units.evaluate(s=>Array.from(s.selectedOptions,o=>o.value)),['11','33']);
    assert.deepEqual(await Promise.all([trial(0).inputValue(),trial(1).inputValue()]),choices);
    await page.locator('[data-ef-jump="1"]:visible').click();
    await page.locator('[data-analysis-signal][aria-pressed=true]').waitFor();
    await page.locator('[data-analysis-tab]').last().click();
    await canvas.waitFor();assert.equal(await panel('L').getAttribute('aria-pressed'),'true');
    assert.deepEqual(await Promise.all([trial(0).inputValue(),trial(1).inputValue()]),choices);
    await panel('J').click();await group.click();await page.locator('[data-ef-group][aria-pressed=false]').waitFor();
    await panel('J').focus();await page.keyboard.press('Escape');
    assert.equal(await panel('review').getAttribute('aria-pressed'),'true');
    assert(await panel('review').evaluate(b=>b===document.activeElement));
    assert.equal(await page.locator('[data-ea-unit]:visible').count(),3);
    await page.locator('[data-analysis-signal]').click();await page.locator('#event-figures-button').click();
    await canvas.waitFor();assert.equal(await page.locator('[data-analysis-tab]').count(),1);
    await panel('review').click();
    await page.locator('[data-ea-inputs] > summary').click();
    await set('eventType').selectOption('cue');await set('conditionField').selectOption('direction');
    await set('referenceValue').selectOption('"right"');await set('comparisonValue').selectOption('"left"');
    await page.locator('[data-ea-unit-choice]').selectOption('manual');await set('unitIds').fill('11,33');await set('unitIds').press('Tab');
    await page.locator('[data-ea-run]').click();await page.waitForFunction(()=>document.querySelectorAll('[data-ea-unit]').length===2);
    await panel('J').click();await canvas.waitFor();
    const rerun=await canvas.getAttribute('aria-label');assert.match(rerun,/2 Units.*cue/);assert.match(rerun,/right.*left/);
    assert.deepEqual(errors,[]);
    console.log('PASS inline event figures: workspace navigation, 390px layout, four distinct white PNGs, grouping, Unit/trial choices, exact-window controls and source return.');
  }finally{await browser.close();}
})().catch(error=>{console.error(error);process.exitCode=1;});
