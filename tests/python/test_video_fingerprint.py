from __future__ import annotations
import copy
import json
import os
from pathlib import Path
import threading
import types
import unittest
from unittest.mock import patch
import urllib.request
import urllib.error

import test_local_projects as fixtures
from neuropixels_explorer import video_fingerprint as V
from neuropixels_explorer.service import create_server
from neuropixels_explorer.ingest import IngestError


class VideoFingerprintTests(unittest.TestCase):
    setUp = fixtures.LocalProjectTests.setUp
    tearDown = fixtures.LocalProjectTests.tearDown

    def video(self, data=b"abc"):
        path = self.root / "private-name.mp4"
        path.write_bytes(data)
        local = self.service.local_projects
        token = local.grant(path)
        project = {"id": "project", "recordingIds": ["recording"], "videos": {"recording": {
            "recording_id": "recording", "video_stream_id": token, "video_name": path.name, "byte_size": len(data)}}}
        local.state["projects"].append(project); local.save()
        return path, {"projectId": "project", "recordingId": "recording", "videoStreamId": token}

    def test_browser_algorithm_parity_empty_small_and_multichunk(self):
        # Expected digests were independently generated by event-analysis-storage.js.
        for data, digest in [(b"", "efc2db53f24490c417137a67026f54b9b6c323c13e966cb9b44eb572278479b0"),
                             (b"abc", "49ff43e0c446441ef7ded4641507e6751cfd38b9844acb18d7e1b9760cadf60e"),
                             (bytes(i % 251 for i in range(2 * V.CHUNK_BYTES + 17)), "d43149b48a3f8bed01b879bd0e8a0ef88c4e7b0c3bd090ded48fe476cf00b0b3")]:
            p = self.root / "parity.mp4"; p.write_bytes(data)
            self.assertEqual(V.fingerprint_path(p), {"algorithm": "sha256-ordered-chunks/1", "chunkBytes": V.CHUNK_BYTES, "size": len(data), "digest": digest})

    def test_size_cap_and_regular_file_before_open(self):
        p, _ = self.video()
        with patch.object(V, "MAX_VIDEO_BYTES", 2), patch.object(Path, "open") as opened:
            with self.assertRaisesRegex(ValueError, "512 MiB"): V.fingerprint_path(p)
            opened.assert_not_called()
        with self.assertRaisesRegex(ValueError, "regular file"): V.fingerprint_path(self.root)

    def mutated_read(self, mutate):
        p, _ = self.video(b"x" * (V.CHUNK_BYTES + 7)); original = Path.open
        class Reader:
            def __init__(self, handle): self.handle, self.changed = handle, False
            def __enter__(self): return self
            def __exit__(self, *args): self.handle.close()
            def fileno(self): return self.handle.fileno()
            def read(self, n):
                if n > V.CHUNK_BYTES: raise AssertionError("Unbounded read")
                value = self.handle.read(n)
                if not self.changed:
                    self.changed = True; mutate(p, original)
                return value
        with patch.object(Path, "open", lambda path, *a, **k: Reader(original(path, *a, **k))):
            with self.assertRaisesRegex(ValueError, "changed|truncated"): V.fingerprint_path(p)

    def test_growth_is_not_read_to_unbounded_eof(self):
        def grow(p, opened):
            with opened(p, "ab") as f: f.write(b"growth")
        self.mutated_read(grow)

    def test_truncation_during_read_rejected(self):
        def truncate(p, opened):
            with opened(p, "r+b") as f: f.truncate(1)
        self.mutated_read(truncate)

    def test_path_replacement_identity_rejected(self):
        p, _ = self.video(); before = p.stat()
        changed = types.SimpleNamespace(**{k: getattr(before, k) for k in ["st_dev", "st_ino", "st_size", "st_mtime_ns", "st_ctime_ns", "st_mode"]})
        changed.st_ino += 1
        with patch.object(Path, "stat", side_effect=[before, changed]):
            with self.assertRaisesRegex(ValueError, "changed"): V.fingerprint_path(p)

    def test_selected_project_binding_metadata_and_no_state_write(self):
        p, payload = self.video(); local = self.service.local_projects; before = local.file.read_bytes()
        result = local.video_fingerprint(payload)
        self.assertEqual(result["fingerprint"]["size"], 3); self.assertEqual(before, local.file.read_bytes())
        self.assertNotIn(str(p), json.dumps(result)); self.assertLess(len(json.dumps(result)), 600)
        for key, value in [("projectId", "other"), ("recordingId", "other"), ("videoStreamId", "f" * 32)]:
            with self.assertRaises(ValueError): local.video_fingerprint({**payload, key: value})
        with self.assertRaises(ValueError): local.video_fingerprint({**payload, "path": str(p)})
        video = local.state["projects"][0]["videos"]["recording"]
        video["recording_id"] = "other"
        with self.assertRaises(ValueError): local.video_fingerprint(payload)
        video["recording_id"] = "recording"; video["byte_size"] = 4
        with self.assertRaisesRegex(ValueError, "metadata"): local.video_fingerprint(payload)

    def test_nonvideo_empty_or_changed_link_rejected_safely(self):
        p, payload = self.video(); local = self.service.local_projects; grant = local.state["assets"][payload["videoStreamId"]]
        grant["path"] = str(self.root / "private-name.txt")
        with self.assertRaisesRegex(ValueError, "not a video"): local.video_fingerprint(payload)
        grant["path"] = str(p)
        os.utime(p, ns=(p.stat().st_atime_ns, p.stat().st_mtime_ns + 1000000))
        with self.assertRaisesRegex(ValueError, "missing or changed") as caught: local.video_fingerprint(payload)
        self.assertNotIn(str(p), str(caught.exception)); self.assertFalse(local.video_fingerprint_lock.locked())
        grant["size"] = 0; local.state["projects"][0]["videos"]["recording"]["byte_size"] = 0
        with self.assertRaisesRegex(ValueError, "nonempty"): local.video_fingerprint(payload)

    def test_rebind_during_hash_rejected_and_lock_released(self):
        _, payload = self.video(); local = self.service.local_projects
        def replace(_):
            local.state["projects"][0]["videos"]["recording"]["video_stream_id"] = "f" * 32
            return {"size": 3}
        with patch("neuropixels_explorer.local_projects.fingerprint_path", side_effect=replace):
            with self.assertRaises(ValueError): local.video_fingerprint(payload)
        self.assertFalse(local.video_fingerprint_lock.locked())

    def test_no_cache_and_busy_is_immediate(self):
        _, payload = self.video(); local = self.service.local_projects
        with patch("neuropixels_explorer.local_projects.fingerprint_path", wraps=V.fingerprint_path) as hashing:
            local.video_fingerprint(payload); local.video_fingerprint(payload)
            self.assertEqual(hashing.call_count, 2)
        local.video_fingerprint_lock.acquire()
        try:
            with self.assertRaises(IngestError) as caught: local.video_fingerprint(payload)
            self.assertEqual(caught.exception.status, 409)
        finally: local.video_fingerprint_lock.release()

    def test_endpoint_same_origin_small_body_and_response(self):
        _, payload = self.video(); server = create_server(self.paths, host="127.0.0.1", port=0, quiet=True)
        thread = threading.Thread(target=server.serve_forever, daemon=True); thread.start()
        origin = "http://127.0.0.1:" + str(server.server_port)
        def send(body, source=origin):
            req = urllib.request.Request(origin + "/api/local/video-fingerprint", data=json.dumps(body).encode(), headers={"Content-Type": "application/json", "Origin": source})
            return urllib.request.urlopen(req, timeout=5)
        try:
            with send(payload) as response: self.assertEqual(json.load(response)["fingerprint"]["size"], 3)
            for body, source, code in [(payload, "https://example.invalid", 403), ({"padding": "x" * 5000}, origin, 413)]:
                with self.assertRaises(urllib.error.HTTPError) as caught: send(body, source)
                self.assertEqual(caught.exception.code, code)
            server.service.local_projects.video_fingerprint_lock.acquire()
            try:
                with self.assertRaises(urllib.error.HTTPError) as caught: send(payload)
                self.assertEqual(caught.exception.code, 409)
            finally: server.service.local_projects.video_fingerprint_lock.release()
        finally:
            server.shutdown(); server.server_close(); server.service.close(); thread.join(timeout=5)


if __name__ == "__main__": unittest.main()
