"use strict";
// Run against a local Explorer containing a representative recording.
// Requires Playwright, ANNOTATION_TEST_URL and ANNOTATION_TEST_VIDEO.
const { chromium } = require("playwright");
const fs = require("node:fs");
const path = require("node:path");
const assert = require("node:assert/strict");
(async () => {
  const output = path.resolve(process.env.ANNOTATION_TEST_OUTPUT || "runtime/annotation-beta");
  fs.mkdirSync(output, { recursive: true });
  const browser = await chromium.launch({ channel: "chrome", headless: true });
  const page = await browser.newPage({ viewport: { width: 1920, height: 1080 }, acceptDownloads: true });
  const errors = []; page.on("pageerror", (e) => errors.push(e.message));
  try {
    await page.goto(process.env.ANNOTATION_TEST_URL || "http://127.0.0.1:8790/?database=1");
    if (process.env.ANNOTATION_TEST_FOLDER) await page.locator("#folder-input").setInputFiles(process.env.ANNOTATION_TEST_FOLDER);
    await page.locator("#explorer-view").waitFor({ state: "visible", timeout: 60000 });
    await page.waitForTimeout(3000);
    console.log(JSON.stringify({ title: await page.title(), inputs: await page.locator('input[type="file"]').evaluateAll((els) => els.map((el) => ({ id: el.id, accept: el.accept }))), errors }));
    await page.screenshot({ path: path.join(output, "01-before-annotation.png") });
    if (!process.env.ANNOTATION_TEST_VIDEO) return;
    await page.locator('input[type="file"][accept*="video"]').setInputFiles(process.env.ANNOTATION_TEST_VIDEO);
    await page.locator("#video-transport").waitFor({ state: "visible" });
    await page.locator("#annotation-toggle").click();
    await page.locator('[data-field="start"]').waitFor();
    assert(await page.locator("#video-play-button").evaluate((el) => {
      const r = el.getBoundingClientRect(), p = document.querySelector("#experiment-video-region").getBoundingClientRect();
      return r.top >= p.top && r.bottom <= p.bottom;
    }), "Video transport must remain visible while annotating");
    await page.locator('[data-field="start"]').fill("1");
    await page.locator('[data-field="end"]').fill("3");
    await page.locator('[data-field="label"]').fill("test grooming");
    await page.locator('[data-action="add"]').click();
    await page.locator("[data-select]").first().click();
    await page.locator('[data-action="confirm"]').click();
    assert.equal(await page.locator(".annotation-review.is-reviewed").count(), 1);
    await page.locator('[data-new-scheme]').fill("Lab B");
    await page.locator('[data-action="scheme"]').click();
    assert.equal(await page.locator(".annotation-review.is-reviewed").count(), 0);
    assert.equal(await page.locator(".annotation-row").count(), 1);
    await page.locator('[data-scheme]').selectOption({ label: "Default" });
    assert.equal(await page.locator(".annotation-review.is-reviewed").count(), 1);
    await page.screenshot({ path: path.join(output, "02-manual-annotation.png") });
    const downloadEvent = page.waitForEvent("download"); await page.locator('[data-action="save"]').click();
    const download = await downloadEvent; await download.saveAs(path.join(output, "ui-project.json"));
    const saved = JSON.parse(fs.readFileSync(path.join(output, "ui-project.json"), "utf8"));
    assert.equal(saved.segments.length, 1);
    assert.equal(saved.schemes.length, 2);
    await page.locator("[data-select]").first().click();
    await page.locator('[data-field="end"]').fill("4");
    await page.locator('[data-action="edit"]').click();
    assert.equal(await page.locator(".annotation-review.is-reviewed").count(), 0);
    await page.locator('[data-action="undo"]').click();
    assert.equal(await page.locator(".annotation-review.is-reviewed").count(), 1);
    await page.locator("[data-select]").first().click();
    await page.locator("#video-seek").evaluate((el) => { el.value = "2"; el.dispatchEvent(new Event("input", { bubbles: true })); });
    await page.locator('[data-action="split"]').click();
    assert.equal(await page.locator(".annotation-row").count(), 2);
    await page.locator('[data-action="page-select"]').click();
    await page.locator('[data-action="merge"]').click();
    assert.equal(await page.locator(".annotation-row").count(), 1);
    await page.locator('[data-import]').setInputFiles(path.join(output, "ui-project.json"));
    assert.equal(await page.locator(".annotation-review.is-reviewed").count(), 1);
    await page.locator("[data-select]").first().click();
    const endHandle = await page.locator('[data-edge="end"]').boundingBox();
    assert(endHandle, "Selected interval exposes a draggable end boundary");
    await page.mouse.move(endHandle.x + endHandle.width / 2, endHandle.y + endHandle.height / 2);
    await page.mouse.down();
    await page.mouse.move(endHandle.x - 80, endHandle.y + endHandle.height / 2, { steps: 6 });
    await page.mouse.up();
    assert(Number(await page.locator('[data-field="end"]').inputValue()) < 3);
    assert.equal(await page.locator(".annotation-review.is-reviewed").count(), 0);
    await page.locator('[data-action="undo"]').click();
    await page.locator("[data-select]").first().click();
    assert.equal(await page.locator('[data-field="end"]').inputValue(), "3.000");
    await page.locator('[data-action="loop"]').click();
    await page.locator("#video-seek").evaluate((el) => { el.value = "2.95"; el.dispatchEvent(new Event("input", { bubbles: true })); });
    await page.waitForFunction(() => { const v = document.querySelector("#behavior-video"); return !v.paused && v.currentTime >= 1 && v.currentTime < 2; });
    await page.locator('[data-action="loop"]').click();
    await page.locator("#behavior-video").evaluate((v) => v.pause());
    assert.match(await page.locator("#annotation-timeline").getAttribute("title"), /unverified|未验证|未核实|sin verificar|no verificada/i);
    const csvEvent = page.waitForEvent("download"); await page.locator('[data-action="csv"]').click();
    await (await csvEvent).saveAs(path.join(output, "ui-export.csv"));
    assert(fs.readFileSync(path.join(output, "ui-export.csv"), "utf8").includes('"unverified"'));
    // The public demo is processed locally; no true behavior accuracy is implied.
    await page.locator(".annotation-algorithm summary").click();
    await page.locator('[data-action="run"]').click();
    await page.locator('[data-action="cancel"]').click();
    await page.waitForFunction(() => !document.querySelector('[data-action="run"]').disabled);
    assert.equal(await page.locator(".annotation-row").count(), 1, "Cancellation must not add partial candidates");
    await page.locator('[data-action="run"]').click();
    await page.waitForFunction(() => document.querySelector("[data-progress]")?.textContent.includes("samples"), null, { timeout: 240000 });
    await page.locator('[data-group]').selectOption({ index: 2 });
    await page.locator('[data-group-name]').fill("Review example");
    await page.locator('[data-action="name"]').click();
    await page.locator('[data-action="page-select"]').click();
    await page.screenshot({ path: path.join(output, "03-group-review.png") });
    await page.locator("[data-samples]").scrollIntoViewIfNeeded();
    await page.waitForFunction(() => [...document.querySelectorAll("[data-samples] video")].every((v) => v.readyState >= 2));
    assert(await page.locator("[data-samples] video").count() > 0);
    await page.screenshot({ path: path.join(output, "07-group-video-previews.png") });
    await page.locator(".annotation-heading").scrollIntoViewIfNeeded();
    const resultsEvent = page.waitForEvent("download"); await page.locator('[data-action="save"]').click();
    await (await resultsEvent).saveAs(path.join(output, "discovery-project.json"));
    const project = JSON.parse(fs.readFileSync(path.join(output, "discovery-project.json"), "utf8"));
    assert(project.segments.length > 1); assert.equal(project.runs.length, 1);
    assert(project.segments.filter((s) => s.runId).every((s) => !project.schemes[0].reviewed[s.id]));
    await page.setViewportSize({ width: 3840, height: 1080 });
    await page.screenshot({ path: path.join(output, "04-ultrawide.png") });
    await page.setViewportSize({ width: 1920, height: 1080 });
    await page.locator("#language-select").selectOption("zh-CN");
    await page.screenshot({ path: path.join(output, "05-chinese.png") });
    await page.reload();
    if (process.env.ANNOTATION_TEST_FOLDER) await page.locator("#folder-input").setInputFiles(process.env.ANNOTATION_TEST_FOLDER);
    await page.locator("#explorer-view").waitFor({ state: "visible", timeout: 60000 });
    await page.locator('input[type="file"][accept*="video"]').setInputFiles(process.env.ANNOTATION_TEST_VIDEO);
    await page.locator("#video-transport").waitFor({ state: "visible" }); await page.locator("#annotation-toggle").click();
    await page.waitForFunction(() => document.querySelector("[data-group]")?.options.length > 2);
    assert.equal(await page.locator("[data-scheme] option").count(), 2, "Browser drafts persist across reloads");
    assert.deepEqual(errors, []);
    console.log(JSON.stringify({ status: "PASS", segments: project.segments.length, runs: project.runs.length, errors, output }, null, 2));
  } catch (error) {
    console.error(JSON.stringify({ videos: await page.locator("video").evaluateAll((els) => els.map((v) => ({ time: v.currentTime, ready: v.readyState, seeking: v.seeking, error: v.error?.message }))) }));
    await page.screenshot({ path: path.join(output, "test-failure.png") });
    throw error;
  } finally { await browser.close(); }
})().catch((error) => { console.error(error); process.exitCode = 1; });
